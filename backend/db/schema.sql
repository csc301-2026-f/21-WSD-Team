PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;

-- Metadata: Known physical storage devices
CREATE TABLE IF NOT EXISTS devices (
    device_id TEXT PRIMARY KEY,
    host_id TEXT NOT NULL,
    display_name TEXT,
    media_type TEXT,            -- 'ssd', 'hdd', or 'unknown'
    capacity_bytes INTEGER,
    free_bytes INTEGER,
    mount_points TEXT,          -- JSON list of mount strings
    is_available INTEGER NOT NULL DEFAULT 1,
    last_seen_utc TEXT NOT NULL
);

-- Telemetry: Time-series samples per storage device
CREATE TABLE IF NOT EXISTS device_metrics (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    device_id TEXT NOT NULL,
    host_id TEXT NOT NULL,
    timestamp_utc TEXT NOT NULL,
    sample_window_seconds REAL NOT NULL,
    read_bytes_per_sec REAL,
    write_bytes_per_sec REAL,
    read_iops REAL,
    write_iops REAL,
    avg_read_latency_ms REAL,
    avg_write_latency_ms REAL,
    source TEXT NOT NULL,
    FOREIGN KEY (device_id) REFERENCES devices(device_id) ON DELETE CASCADE
);

-- Fast lookup composite index for device history queries
CREATE INDEX IF NOT EXISTS idx_device_metrics_lookup 
ON device_metrics(device_id, timestamp_utc);

-- Telemetry: Time-series samples per application/process
CREATE TABLE IF NOT EXISTS process_metrics (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    process_instance_id TEXT NOT NULL,  -- f"{pid}_{start_time_utc}"
    host_id TEXT NOT NULL,
    pid INTEGER NOT NULL,
    start_time_utc TEXT,
    process_name TEXT,
    timestamp_utc TEXT NOT NULL,
    sample_window_seconds REAL NOT NULL,
    read_bytes_per_sec REAL,
    write_bytes_per_sec REAL,
    attributed_device_id TEXT
);

-- Fast lookup composite index for US-02 process history
CREATE INDEX IF NOT EXISTS idx_process_metrics_lookup 
ON process_metrics(process_instance_id, timestamp_utc);

-- Storage Recommendations (Generated by ALGO)
CREATE TABLE IF NOT EXISTS recommendations (
    recommendation_id TEXT PRIMARY KEY,
    mode TEXT NOT NULL,                 -- 'raid0' or 'ssd_caching'
    action TEXT NOT NULL,               -- 'move', 'cache', 'evict', 'none'
    file_id TEXT,
    source_device_id TEXT,
    target_device_id TEXT,
    reason TEXT NOT NULL,
    created_at_utc TEXT NOT NULL,
    requires_approval INTEGER NOT NULL DEFAULT 1,
    estimated_benefit TEXT,             -- JSON object
    constraints TEXT                    -- JSON list
);

-- Key-value settings storage (for US-06 auto mode and thresholds)
CREATE TABLE IF NOT EXISTS app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at_utc TEXT NOT NULL
);